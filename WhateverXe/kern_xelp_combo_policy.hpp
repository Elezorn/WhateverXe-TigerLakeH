 static Table choose(Platform platform,uint32_t rate,bool panel,bool lowSwing,bool useHOBL) {
  if(platform==Platform::Unknown || platform>Platform::ADLP ||
     (rate!=6 && rate!=10 && rate!=20 && rate!=30))return Table::Invalid;
  if(panel) {
   if(rate==30)return platform==Platform::ADLS?Table::ADLSHigh:platform==Platform::ADLP?Table::ADLPHigh:Table::ICLHigh;
   if(useHOBL)return Table::HOBL;
   if(lowSwing)return platform==Platform::ADLS?Table::ADLSLow:platform==Platform::ADLP?Table::ADLPLow:Table::LowSwing;
  }
  if(platform==Platform::ADLP)return rate>10?Table::ADLPHigh:Table::ADLPHBR;
  if(platform==Platform::RKL)return rate>10?Table::RKLHigh:Table::RKLHBR;
  if(rate<=10)return Table::TGLHBR;
  return platform==Platform::ADLS?Table::ADLSHigh:platform==Platform::TGLUY?Table::TGLUYHigh:Table::TGLHigh;
 }
