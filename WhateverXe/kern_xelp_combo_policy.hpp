 bool select(Platform platform,uint32_t rate,bool panel,bool lowSwing,bool useHOBL,uint32_t voltage,uint32_t emphasis) {
  *this={};
  if(voltage>3 || emphasis>3 || voltage+emphasis>3)return false;
  const auto chosen=choose(platform,rate,panel,lowSwing,useHOBL);
  if(chosen==Table::Invalid)return false;
  static const uint8_t first[]={0,4,7,9};
  const auto requested=first[voltage]+emphasis;
  // Linux intel_ddi_level clamps to the final table entry. HOBL has nine
  // identical entries and no distinct voltage-3 row.
  level=chosen==Table::HOBL && requested>=9?8:requested;
  if(!row(chosen,level,coefficients)){*this={};return false;}
  table=chosen;hobl=chosen==Table::HOBL;return true;
 }
